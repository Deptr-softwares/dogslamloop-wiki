#!/usr/bin/env node
/**
 * Stamps a content hash onto EVERY js/ module in every page's <script src>.
 *
 * The bug this exists for, 2026-08-10: GitHub Pages serves js/ with
 * max-age=3600. A deploy that adds a new module depending on a new shared
 * helper therefore gives the browser a *fresh* copy of the new file and an
 * *hour-old* copy of site_utils.js. The new file called a helper the cached
 * copy did not have, the TypeError went straight through edit.html's boot
 * try/catch, and the editor was dead for every contributor who had the site
 * open - reported on the live site within minutes of the merge.
 *
 * A query string on the URL makes it a different cache key, so the moment the
 * hash changes every browser fetches the new file.
 *
 * This used to stamp three modules only, on the reasoning that "a page and its
 * own script are always deployed together". That holds in the repository and
 * not in the cache - HTML is max-age=600 and js/ is max-age=3600 - and it cost
 * three releases, the worst being v0.16, whose roster changes were invisible on
 * the live site because js/pagebuilder.js was unstamped. Every module is
 * stamped now, and the list is discovered rather than hand-kept. See
 * scripts/asset-version.js for why they share one version.
 *
 * Generated stubs are stamped by scripts/generate-pages.js itself, from the
 * same helper, so `generate-pages --check` and this script agree. This script
 * only rewrites the hand-authored pages.
 *
 * Usage:
 *   node scripts/stamp-assets.js            # report only (same as --check)
 *   node scripts/stamp-assets.js --check    # exit 1 if any page is stale
 *   node scripts/stamp-assets.js --write    # write the files
 */

const fs = require('fs');
const path = require('path');
const { sharedAssetVersion, stampSharedAssets, SHARED_MODULES } = require('./asset-version.js');

const ROOT = path.join(__dirname, '..');

// Every .html that is not a generated stub. Generated stubs live exactly two
// levels down under a page directory and carry the generator's marker, so
// excluding them by marker rather than by path keeps the two scripts from
// disagreeing about which files they each own.
const GENERATED_MARKER = 'GENERATED by scripts/generate-pages.js';

function collectHtml(dir, out = []) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        if (entry.name === 'node_modules' || entry.name === '.git' || entry.name === 'test-results') continue;
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) collectHtml(full, out);
        else if (entry.isFile() && entry.name.endsWith('.html')) out.push(full);
    }
    return out;
}

function main() {
    const write = process.argv.includes('--write');
    const version = sharedAssetVersion();

    const stale = [];
    let checked = 0;

    for (const file of collectHtml(ROOT)) {
        const before = fs.readFileSync(file, 'utf8');
        if (before.includes(GENERATED_MARKER)) continue;
        if (!/src="[^"]*js\/site_utils\.js/.test(before)) continue;

        checked++;
        const after = stampSharedAssets(before, version);
        if (after === before) continue;

        stale.push(path.relative(ROOT, file).replace(/\\/g, '/'));
        if (write) fs.writeFileSync(file, after);
    }

    // A count, not the list. Every module in js/ is stamped now, so naming them
    // all made the one line of output unreadable and buried the pass/fail.
    const label = `stamp-assets: ${SHARED_MODULES.length} modules v${version}`;

    if (stale.length === 0) {
        console.log(`${label} - up to date (${checked} hand-authored page(s)).`);
        return;
    }

    if (write) {
        stale.forEach(f => console.log(`  stamped ${f}`));
        console.log(`${label} - stamped ${stale.length} of ${checked} page(s).`);
        return;
    }

    stale.forEach(f => console.log(`  STALE ${f}`));
    console.error(`${label} - ${stale.length} page(s) carry an old or missing version. Run: npm run generate`);
    process.exit(1);
}

if (require.main === module) main();

module.exports = { collectHtml };
