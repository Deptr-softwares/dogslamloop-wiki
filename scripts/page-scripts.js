// GitHub Pages serves 404.html at whatever address was asked for, so its tags
// start at the site root. Every other page's start from where it sits.
function prefixFor(file) {
    return file === '404.html' ? '/' : '../'.repeat(file.split('/').length - 1);
}

/**
 * The script tags for one kind of page, one per line, unstamped.
 * @param {string} kind a key of PAGE_SCRIPTS
 * @param {string} prefix what goes before "js/": '../../' on a generated page
 * @param {{own?: string|null}} [options] own: a tool page's own script, under js/
 * @watch throws on a kind with no list, so a page is never written without one
 */
function scriptTags(kind, prefix, { own = null } = {}) {
    const list = PAGE_SCRIPTS[kind];
    if (!list) throw new Error(`page-scripts: no script list for the page kind "${kind}"`);
    return list
        .flatMap(entry => (entry === OWN ? (own ? [own] : []) : [entry]))
        .map(entry => {
            const { src, async: isAsync, defer } = typeof entry === 'string' ? { src: entry } : entry;
            const flag = isAsync ? 'async ' : (defer ? 'defer ' : '');
            return `    <script ${flag}src="${prefix}js/${src}"></script>`;
        })
        .join('\n');
}

/**
 * The stylesheet tags for one kind of page, one per line, unstamped.
 * @param {string} kind a key of PAGE_STYLES
 * @param {string} prefix what goes before "style/": '../../' on a generated page
 * @param {{own?: string|null}} [options] own: a tool page's own sheet, under style/
 * @watch throws on a kind with no list, so a page is never written without one
 */
function styleTags(kind, prefix, { own = null } = {}) {
    const list = PAGE_STYLES[kind];
    if (!list) throw new Error(`page-scripts: no stylesheet list for the page kind "${kind}"`);
    return list
        .flatMap(entry => (entry === OWN ? (own ? [own] : []) : [entry]))
        .map(href => `    <link rel="stylesheet" href="${prefix}style/${href}">`)
        .join('\n');
}

const SCRIPT_TAG = /<script\b[^>]*\ssrc=/;
const STYLESHEET_TAG = /<link\b[^>]*\srel="stylesheet"/;

// One marked block rewritten, or an error message.
function rewriteMarked(html, file, { begin, end, tags, tag, what }) {
    const start = html.indexOf(begin);
    const stop = html.indexOf(end);
    if (start < 0 || stop < start || html.indexOf(begin, start + 1) >= 0 || html.indexOf(end, stop + 1) >= 0) {
        return { error: `${file} needs exactly one ${begin} ... ${end} block` };
    }
    const after = `${html.slice(0, start)}${begin}\n${tags}\n    ${html.slice(stop)}`;
    const outside = after.slice(0, start) + after.slice(after.indexOf(end));
    if (tag.test(outside)) {
        return { error: `${file} has a ${what} tag outside its block: add it to its list in scripts/page-scripts.js` };
    }
    return { html: after };
}

// The page with its scripts block rewritten, or an error message.
function rewriteBlock(html, file, version) {
    const tags = stampSharedAssets(scriptTags(HAND_WRITTEN[file], prefixFor(file)), version);
    return rewriteMarked(html, file, { begin: BEGIN, end: END, tags, tag: SCRIPT_TAG, what: 'script' });
}

// The page with its styles block rewritten, or an error message.
function rewriteStyles(html, file, version) {
    const tags = stampSharedAssets(styleTags(HAND_WRITTEN[file], prefixFor(file)), version);
    return rewriteMarked(html, file, { begin: STYLES_BEGIN, end: STYLES_END, tags, tag: STYLESHEET_TAG, what: 'stylesheet' });
}

// The page with both blocks rewritten, or the first error.
function rewritePage(html, file, version) {
    const scripts = rewriteBlock(html, file, version);
    return scripts.error ? scripts : rewriteStyles(scripts.html, file, version);
}

function main() {
    const write = process.argv.includes('--write');
    const version = sharedAssetVersion();
    const problems = [];
    const stale = [];

    // A page that loads scripts or stylesheets and is in neither list would be
    // the one page whose tags nothing checks.
    for (const abs of collectHtml(ROOT)) {
        const file = path.relative(ROOT, abs).replace(/\\/g, '/');
        const html = fs.readFileSync(abs, 'utf8');
        if (html.includes(GENERATED_PAGE) || HAND_WRITTEN[file]) continue;
        if (SCRIPT_TAG.test(html)) problems.push(`${file} loads scripts but is not in HAND_WRITTEN`);
        if (STYLESHEET_TAG.test(html)) problems.push(`${file} loads stylesheets but is not in HAND_WRITTEN`);
    }

    for (const file of Object.keys(HAND_WRITTEN)) {
        const abs = path.join(ROOT, file);
        const before = fs.readFileSync(abs, 'utf8');
        const { html, error } = rewritePage(before, file, version);
        if (error) { problems.push(error); continue; }
        if (html === before) continue;
        stale.push(file);
        if (write) fs.writeFileSync(abs, html);
    }

    if (problems.length) {
        console.error('page-scripts FAILED:');
        problems.forEach(p => console.error(`  - ${p}`));
        process.exit(1);
    }
    const count = Object.keys(HAND_WRITTEN).length;
    if (stale.length === 0) {
        console.log(`page-scripts: ${count} hand-written page(s) up to date.`);
        return;
    }
    if (write) {
        stale.forEach(f => console.log(`  wrote ${f}`));
        console.log(`page-scripts: rewrote ${stale.length} of ${count} page(s).`);
        return;
    }
    stale.forEach(f => console.log(`  STALE ${f}`));
    console.error(`page-scripts: ${stale.length} page(s) do not match their list. Run: npm run generate`);
    process.exit(1);
}

if (require.main === module) main();

