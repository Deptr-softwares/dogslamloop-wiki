// One script list and one stylesheet list per kind of page
// (scripts/page-scripts.js). The generator writes a generated page's tags from
// them, and each hand-written page has two marked blocks that npm run generate
// rewrites. This holds the pages to them, so a file renamed or added changes one
// list, not 74 pages. Node only.
const { test, expect } = require('@playwright/test');
const fs = require('fs');
const path = require('path');

const {
    PAGE_SCRIPTS, PAGE_STYLES, HAND_WRITTEN, scriptTags, styleTags, rewriteBlock, rewriteStyles, rewritePage,
    BEGIN, END, STYLES_BEGIN, STYLES_END,
} = require('../scripts/page-scripts.js');
const { buildPages, PAGE_DIRECTORIES } = require('../scripts/generate-pages.js');
const { GENERATED_PAGE_TYPES } = require('../scripts/page-types.js');
const { sharedAssetVersion } = require('../scripts/asset-version.js');
const { collectHtml } = require('../scripts/stamp-assets.js');

const ROOT = path.join(__dirname, '..');
const version = sharedAssetVersion();
const srcsOf = html => [...html.matchAll(/<script\b[^>]*\ssrc="([^"?]+)/g)].map(m => m[1]);
const sheetsOf = html => [...html.matchAll(/<link\b[^>]*\srel="stylesheet"[^>]*\shref="([^"?]+)/g)].map(m => m[1]);

test('each hand-written page loads exactly what its lists write, from one block of each', () => {
    for (const [file, kind] of Object.entries(HAND_WRITTEN)) {
        const html = fs.readFileSync(path.join(ROOT, file), 'utf8');
        const result = rewritePage(html, file, version);
        expect(result.error, file).toBeUndefined();
        expect(result.html === html, `${file} matches the "${kind}" lists`).toBe(true);
        expect(srcsOf(html).length, `${file} loads its scripts`).toBeGreaterThan(5);
        expect(sheetsOf(html).length, `${file} loads its stylesheets`).toBeGreaterThan(5);
    }
});

test('a stylesheet tag outside the styles block, or a page without one, is refused', () => {
    const page = `<head>\n    ${STYLES_BEGIN}\n    ${STYLES_END}\n</head>`;
    expect(sheetsOf(rewriteStyles(page, 'search.html', version).html)).toEqual(sheetsOf(styleTags('search', '')));
    const extra = page.replace('</head>', '    <link rel="stylesheet" href="style/extra.css">\n</head>');
    expect(rewriteStyles(extra, 'search.html', version).error).toMatch(/stylesheet tag outside its block/);
    expect(rewriteStyles('<head></head>', 'search.html', version).error).toMatch(/exactly one/);
    expect(rewriteStyles(page + page, 'search.html', version).error).toMatch(/exactly one/);
});

test('a script tag outside the block, or a page without one, is refused', () => {
    const page = `<body>\n    ${BEGIN}\n    ${END}\n</body>`;
    expect(rewriteBlock(page, 'search.html', version).html).toContain('js/pages/records/search-page.js');
    const extra = page.replace('</body>', '    <script src="js/pages/records/extra.js"></script>\n</body>');
    expect(rewriteBlock(extra, 'search.html', version).error).toMatch(/outside its block/);
    expect(rewriteBlock('<body></body>', 'search.html', version).error).toMatch(/exactly one/);
    expect(rewriteBlock(page + page, 'search.html', version).error).toMatch(/exactly one/);
});

test('every page that loads a script or a stylesheet is generated or has a list', () => {
    const unlisted = collectHtml(ROOT)
        .map(abs => path.relative(ROOT, abs).replace(/\\/g, '/'))
        .filter(file => !HAND_WRITTEN[file])
        .filter(file => {
            const html = fs.readFileSync(path.join(ROOT, file), 'utf8');
            return (srcsOf(html).length > 0 || sheetsOf(html).length > 0)
                && !html.includes('GENERATED by scripts/generate-pages.js');
        });
    expect(unlisted).toEqual([]);
});

test('every list is used, by a generated page type or a hand-written page', () => {
    const used = new Set([...GENERATED_PAGE_TYPES, ...Object.values(HAND_WRITTEN)]);
    expect(Object.keys(PAGE_SCRIPTS).sort()).toEqual([...used].sort());
    // The archived and moved pages' notice loads stylesheets and no scripts.
    expect(Object.keys(PAGE_STYLES).sort()).toEqual([...used, 'notice'].sort());
});

test('a generated page loads its type\'s list, and a tool its own script after the host', () => {
    const entry = (pageId, pageType) => ({
        name: pageId, url: `${PAGE_DIRECTORIES[0]}/${pageId}/index.html`, cms_config: { pageId, pageType },
    });
    const made = [...GENERATED_PAGE_TYPES].map(type => entry(`probe_${type}`, type));
    made.push(entry('probe_own', 'tool'));
    const { pages, problems } = buildPages({ Probe: made }, {}, {}, new Set(['probe_own']));
    expect(problems).toEqual([]);

    for (const page of pages) {
        const own = page.pageId === 'probe_own' ? 'pages/tools/probe_own.js' : null;
        expect(srcsOf(page.html), page.pageId).toEqual(srcsOf(scriptTags(page.pageType, '../../', { own })));
    }
    const withOwn = srcsOf(pages.find(p => p.pageId === 'probe_own').html);
    const host = withOwn.indexOf('../../js/pages/types/tool_page.js');
    expect(withOwn[host + 1]).toBe('../../js/pages/tools/probe_own.js');
    expect(withOwn[withOwn.length - 2]).toBe('../../js/pages/core/page_boot.js');
    expect(srcsOf(pages.find(p => p.pageId === 'probe_tool').html).join()).not.toContain('pages/tools/');
});

test('a generated page loads its type\'s stylesheets, a tool its own sheet before Classic, a notice the four', () => {
    const entry = (pageId, pageType) => ({
        name: pageId, url: `${PAGE_DIRECTORIES[0]}/${pageId}/index.html`, cms_config: { pageId, pageType },
    });
    const made = [...GENERATED_PAGE_TYPES].map(type => entry(`probe_${type}`, type));
    made.push(entry('probe_own', 'tool'));
    const archived = { probe_gone: { url: `${PAGE_DIRECTORIES[0]}/probe_gone/index.html`, name: 'Gone' } };
    const moved = { [`${PAGE_DIRECTORIES[0]}/probe_old/index.html`]: 'probe_character' };
    const { pages, problems } = buildPages({ Probe: made }, {}, archived, new Set(), new Set(['probe_own']), moved);
    expect(problems).toEqual([]);

    for (const page of pages.filter(p => !p.archived && !p.moved)) {
        const own = page.pageId === 'probe_own' ? 'tools/probe_own.css' : null;
        expect(sheetsOf(page.html), page.pageId).toEqual(sheetsOf(styleTags(page.pageType, '../../', { own })));
    }
    const withOwn = sheetsOf(pages.find(p => p.pageId === 'probe_own').html);
    expect(withOwn.slice(-1)).toEqual(['../../style/tools/probe_own.css']);
    expect(sheetsOf(pages.find(p => p.pageId === 'probe_tool').html).join()).not.toContain('style/tools/');

    const notices = pages.filter(p => p.archived || p.moved);
    expect(notices).toHaveLength(2);
    for (const page of notices) {
        expect(sheetsOf(page.html), page.relPath).toEqual(sheetsOf(styleTags('notice', '../../')));
    }
});
