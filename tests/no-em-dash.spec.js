// No em-dash in anything this repo writes for the site (CLAUDE.md, Conventions:
// the owner banned it outright). Every script, stylesheet and hand-written page,
// comments included. Node only.
//
// Generated pages and site_lookups.js's generated region are left out: they carry
// the owner's own content, and a dash typed there must never turn CI red.
const { test, expect } = require('@playwright/test');
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.join(__dirname, '..');

// The character, its two HTML entities, and the escape a script could build it from.
const DASH = /—|&mdash;|&#8212;|\\u2014/i;

const FILES = execSync('git ls-files "js/**" "style/**" "*.html"', { cwd: ROOT }).toString()
    .trim().split('\n')
    .filter(file => /\.(js|css|html)$/.test(file) && !file.startsWith('js/vendor/'));

// What is left of a file once the owner's content is taken out, or null for a
// generated page, which is all owner content around a template.
function ownText(file) {
    const text = fs.readFileSync(path.join(ROOT, file), 'utf8');
    if (text.includes('GENERATED by scripts/generate-pages.js')) return null;
    return text.replace(/GENERATED REGION[\s\S]*?END GENERATED REGION/g, '');
}

test('the files checked are the site\'s own', () => {
    // A list that came back empty would pass the test below.
    expect(FILES).toContain('edit.html');
    expect(FILES).toContain('js/utility/site_utils.js');
    expect(FILES).toContain('style/Layout.css');
});

test('no em-dash in a script, a stylesheet or a hand-written page', () => {
    const found = [];
    for (const file of FILES) {
        const text = ownText(file);
        if (text === null) continue;
        text.split('\n').forEach((line, i) => {
            if (DASH.test(line)) found.push(`${file}:${i + 1}: ${line.trim().slice(0, 80)}`);
        });
    }
    expect(found).toEqual([]);
});
